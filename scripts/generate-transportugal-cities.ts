import { writeFileSync } from "node:fs"
import { resolve } from "node:path"
import { ibge } from "brasilapi-sdk"

const OUTPUT_PATH = resolve(
  import.meta.dirname,
  "../websites/transportugal/src/data/brazil-cities.generated.ts"
)

type BrazilCityRow = { cidade: string; uf: string }

const main = async () => {
  const estados = await ibge().getEstados(),
    rows: BrazilCityRow[] = []

  for (const estado of estados) {
    const municipios = await ibge().getMunicipios(estado.sigla)
    for (const municipio of municipios)
      rows.push({ cidade: municipio.nome, uf: estado.sigla })
  }

  rows.sort((a, b) =>
    a.uf === b.uf
      ? a.cidade.localeCompare(b.cidade, "pt-BR")
      : a.uf.localeCompare(b.uf)
  )

  const body = rows
      .map(
        row =>
          `  { cidade: ${JSON.stringify(row.cidade)}, uf: ${JSON.stringify(row.uf)} },`
      )
      .join("\n"),
    contents = `// Generated by \`bun run scripts/generate-transportugal-cities.ts\`.
// Do not hand-edit — regenerate instead. Source: brasilapi-sdk (IBGE).

export type BrazilCity = { cidade: string; uf: string }

export const BRAZIL_CITIES: BrazilCity[] = [
${body}
]
`

  writeFileSync(OUTPUT_PATH, contents, "utf-8")
  console.log(`Wrote ${rows.length} cities to ${OUTPUT_PATH}`)
}

main().catch(err => {
  console.error(err)
  process.exitCode = 1
})
